  function detectInitialLang(){
    try{
      const saved = localStorage.getItem(LANG_STORAGE_KEY);
      if(saved){
        const parsed = JSON.parse(saved);
        if(SUPPORTED_LANGS.indexOf(parsed) !== -1) return parsed;
      }
    }catch(e){ /* localStorage indisponible ou valeur corrompue : ignore, reste sur le défaut */ }
    return DEFAULT_LANG;
  }

  let currentLang = detectInitialLang();
  const listeners = [];

  function t(key, vars){
    const dict = translations[currentLang] || translations[DEFAULT_LANG];
    let str = dict[key];
    if(str === undefined) str = (translations[DEFAULT_LANG] || {})[key];
    if(str === undefined) return key;
    if(vars){
      Object.keys(vars).forEach(k=>{
        str = str.split("{" + k + "}").join(vars[k]);
      });
    }
    return str;
  }

  function getLang(){ return currentLang; }

  function localeTag(){ return LOCALE_TAGS[currentLang] || LOCALE_TAGS[DEFAULT_LANG]; }

  function flag(lang){ return LANG_FLAGS[lang || currentLang] || ""; }

  function setLang(lang){
    if(SUPPORTED_LANGS.indexOf(lang) === -1 || lang === currentLang) return;
    currentLang = lang;
    try{ localStorage.setItem(LANG_STORAGE_KEY, JSON.stringify(lang)); }catch(e){ /* stockage indisponible : la langue reste active pour la session en cours */ }
    listeners.forEach(fn=>{ try{ fn(currentLang); }catch(e){ console.error("[LyonI18n] listener error", e); } });
  }

  function onChange(fn){ listeners.push(fn); }

  window.LyonI18n = {
    t, getLang, setLang, onChange, localeTag, flag,
    SUPPORTED_LANGS, DEFAULT_LANG,
  };
